import os as _os
_HERE = _os.path.dirname(_os.path.abspath(__file__))
PKG_ROOT = _HERE
for _ in range(1):
    PKG_ROOT = _os.path.dirname(PKG_ROOT)
PKG_RESULTS = _os.path.join(PKG_ROOT, "results")
DATA_DIR = _os.environ.get("TCGA_DATA_DIR", _os.path.join(PKG_ROOT, "data"))
# -------------------------------------------------------------------
"""
fix_depmap_edges.py -- regenerate results/depmap_edges_d454.json with the CORRECT
gene column.

Background
----------
The cross-domain (DepMap -> BRCA) retained-edge list in the replication package was
originally written with the wrong gene column ("mad_top500[:454]", which does not
correspond to the row/column order of the saved weight matrices).  The *weights*
were consistent with the matrices, but the gene *labels* were shifted, so the file
disagreed with Section 5.1 of the manuscript (which is correct).

This script rebuilds the file from the weight matrices using the verified gene
column data/genecol_brca454.npy (454 symbols).

Reproduces the manuscript numbers: 20 DepMap source edges at tau=0.3, of which 7
(35.0%) are retained by DepMap-warm, namely
    HES2->GPX2, PCSK9->SERPINB5, S100P->PPP1R14C, POF1B->KRT16,
    TSPAN8->PCSK9, SLC44A4->TSPAN8, USP9Y->POF1B
"""
import json
import os

import numpy as np

BASE = PKG_ROOT
RES = os.path.join(BASE, "results")
TAU = 0.3


def main():
    genes = [str(g) for g in np.load(os.path.join(BASE, "data", "genecol_brca454.npy"),
                                     allow_pickle=True)]
    d = len(genes)
    assert d == 454, d

    W_src = np.load(os.path.join(RES, "W_depmap_d454.npy"))
    W_warm = np.load(os.path.join(RES, "W_dm_warm_d454.npy"))
    assert W_src.shape == (d, d) and W_warm.shape == (d, d)

    src_edges = [(i, j, float(W_src[i, j]))
                 for i in range(d) for j in range(d)
                 if i != j and abs(W_src[i, j]) > TAU]

    retained, lost = [], []
    for i, j, w in src_edges:
        rec = {"src": genes[i], "tgt": genes[j],
               "w_src": w, "w_tgt": float(W_warm[i, j])}
        (retained if abs(W_warm[i, j]) > TAU else lost).append(rec)

    out = {
        "d": d,
        "tau": TAU,
        "gene_column": "data/genecol_brca454.npy (454 symbols, verified against the "
                       "row/column order of the weight matrices)",
        "n_source_edges": len(src_edges),
        "n_retained": len(retained),
        "retention_pct": round(100.0 * len(retained) / len(src_edges), 1),
        "retained_edges": retained,
        "lost_edges": lost,
        "note": "Regenerated by scripts/fix_depmap_edges.py; an earlier version of "
                "this file used the wrong gene column and mislabelled the retained "
                "edges. The weights were always correct.",
    }
    p = os.path.join(RES, "depmap_edges_d454.json")
    json.dump(out, open(p, "w"), indent=1)

    print("source edges:", len(src_edges))
    print("retained: %d (%.1f%%)" % (len(retained), out["retention_pct"]))
    for r in retained:
        print("   %s -> %s  (w_src=%.4f, w_warm=%.4f)"
              % (r["src"], r["tgt"], r["w_src"], r["w_tgt"]))
    print("saved", p)


if __name__ == "__main__":
    main()
